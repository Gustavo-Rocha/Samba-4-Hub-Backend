CREATE TABLE instrumento (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    nome character varying(50) NOT NULL,
    categoria integer NOT NULL,
    data_criacao timestamp with time zone NOT NULL,
    data_atualizacao timestamp with time zone,
    CONSTRAINT pk_instrumento PRIMARY KEY (id)
);

CREATE TABLE usuario (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    email character varying(150) NOT NULL,
    senha_hash character varying(255) NOT NULL,
    telefone character varying(20) NOT NULL,
    cpf_cnpj character varying(14) NOT NULL,
    tipo integer NOT NULL,
    data_criacao timestamp with time zone NOT NULL,
    data_atualizacao timestamp with time zone,
    CONSTRAINT pk_usuario PRIMARY KEY (id)
);

CREATE TABLE perfil_contratante (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    usuario_id bigint NOT NULL,
    nome_responsavel character varying(100) NOT NULL,
    tipo integer NOT NULL,
    nome_comercial character varying(120),
    cnpj character varying(14),
    cidade character varying(100) NOT NULL,
    bairro character varying(80),
    estado character varying(2) NOT NULL,
    data_criacao timestamp with time zone NOT NULL,
    data_atualizacao timestamp with time zone,
    CONSTRAINT pk_perfil_contratante PRIMARY KEY (id),
    CONSTRAINT fk_perfil_contratante_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT
);

CREATE TABLE perfil_musico (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    usuario_id bigint NOT NULL,
    nome_artistico character varying(100) NOT NULL,
    bio character varying(1000),
    modalidade integer NOT NULL,
    cache_minimo numeric(10,2),
    cache_grupo_minimo numeric(10,2),
    cidade character varying(100) NOT NULL,
    estado character varying(2) NOT NULL,
    link_instagram character varying(255),
    link_youtube character varying(255),
    ativo boolean NOT NULL,
    data_criacao timestamp with time zone NOT NULL,
    data_atualizacao timestamp with time zone,
    CONSTRAINT pk_perfil_musico PRIMARY KEY (id),
    CONSTRAINT fk_perfil_musico_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT
);

CREATE TABLE vaga (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    contratante_id bigint NOT NULL,
    titulo character varying(120) NOT NULL,
    descricao character varying(4000) NOT NULL,
    estilo_predominante integer NOT NULL,
    formato_solicitado integer NOT NULL,
    data_evento date NOT NULL,
    hora_inicio time without time zone NOT NULL,
    hora_fim time without time zone NOT NULL,
    logradouro character varying(200) NOT NULL,
    bairro character varying(80) NOT NULL,
    cidade character varying(100) NOT NULL,
    estado character varying(2) NOT NULL,
    cache_oferecido numeric(10,2),
    cache_a_combinar boolean NOT NULL,
    possui_equipamento_som boolean NOT NULL,
    status integer NOT NULL,
    data_criacao timestamp with time zone NOT NULL,
    data_atualizacao timestamp with time zone,
    CONSTRAINT pk_vaga PRIMARY KEY (id),
    CONSTRAINT fk_vaga_perfil_contratante FOREIGN KEY (contratante_id) REFERENCES perfil_contratante (id) ON DELETE RESTRICT
);

CREATE TABLE musico_instrumento (
    perfil_musico_id bigint NOT NULL,
    instrumento_id bigint NOT NULL,
    eh_principal boolean NOT NULL,
    CONSTRAINT pk_musico_instrumento PRIMARY KEY (perfil_musico_id, instrumento_id),
    CONSTRAINT fk_musico_instrumento_instrumento FOREIGN KEY (instrumento_id) REFERENCES instrumento (id) ON DELETE CASCADE,
    CONSTRAINT fk_musico_instrumento_perfil_musico FOREIGN KEY (perfil_musico_id) REFERENCES perfil_musico (id) ON DELETE CASCADE
);

CREATE TABLE candidatura (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    vaga_id bigint NOT NULL,
    musico_id bigint NOT NULL,
    valor_proposta numeric(10,2) NOT NULL,
    mensagem character varying(500),
    status integer NOT NULL,
    data_resposta timestamp with time zone,
    data_criacao timestamp with time zone NOT NULL,
    data_atualizacao timestamp with time zone,
    CONSTRAINT pk_candidatura PRIMARY KEY (id),
    CONSTRAINT fk_candidatura_perfil_musico FOREIGN KEY (musico_id) REFERENCES perfil_musico (id) ON DELETE RESTRICT,
    CONSTRAINT fk_candidatura_vaga FOREIGN KEY (vaga_id) REFERENCES vaga (id) ON DELETE RESTRICT
);

CREATE TABLE vaga_instrumento (
    vaga_id bigint NOT NULL,
    instrumento_id bigint NOT NULL,
    CONSTRAINT pk_vaga_instrumento PRIMARY KEY (vaga_id, instrumento_id),
    CONSTRAINT fk_vaga_instrumento_instrumento FOREIGN KEY (instrumento_id) REFERENCES instrumento (id) ON DELETE CASCADE,
    CONSTRAINT fk_vaga_instrumento_vaga FOREIGN KEY (vaga_id) REFERENCES vaga (id) ON DELETE CASCADE
);

CREATE TABLE interacao_contato (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    candidatura_id bigint NOT NULL,
    iniciado_por integer NOT NULL,
    data_clique timestamp with time zone NOT NULL,
    data_criacao timestamp with time zone NOT NULL,
    data_atualizacao timestamp with time zone,
    CONSTRAINT pk_interacao_contato PRIMARY KEY (id),
    CONSTRAINT fk_interacao_contato_candidatura FOREIGN KEY (candidatura_id) REFERENCES candidatura (id) ON DELETE RESTRICT
);

